#!/usr/bin/env python3
"""Write web_app/common-taxonomy.js from Codex's current definition (owner 2026-11-09 queue item 5, Codex #525 731e4682).

The one dictionary the screens show names and definitions from is common_classification.catalog.current_taxonomy() (투자시스템 공통
10섹터, common-classification-definition/1; TELECOMMUNICATIONS = 통신서비스), embedded as is. It changes display only: classification
records keep their own dictionary / mapping versions and hashes. --check fails when the embedded copy differs from a fresh call.

  python implementation/tools/common_taxonomy_main.py [--check]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'implementation' / 'src'))
from investment_system.research.common_classification.catalog import current_taxonomy  # noqa: E402

OUT = ROOT / 'implementation' / 'src' / 'investment_system' / 'product' / 'web_app' / 'common-taxonomy.js'
HEAD = """/* The one common dictionary for display (IS2.taxonomy; owner 2026-11-09 queue item 5): Codex #525 catalog.current_taxonomy() as is
   (투자시스템 공통 10섹터, common-classification-definition/1, investment-system-common-10-sector/1; TELECOMMUNICATIONS = 통신서비스).
   Generated by tools/common_taxonomy_main.py; do not edit by hand (the --check run and the node test compare it with Codex's call and
   Codex's public fixture taxonomy.json). Names and definitions only: a classification record keeps its own dictionary and mapping
   versions and its hash; nothing here re-classifies or re-hashes a record. An id the definition does not know is shown as the id. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else{const I=root.IS2=root.IS2||{};I.taxonomy=api;}})(typeof globalThis==='object'?globalThis:this,function(){
'use strict';
const DATA="""
TAIL = """;
function deepFreeze(v){if(v&&typeof v==='object'&&!Object.isFrozen(v)){Object.freeze(v);for(const x of Object.values(v))deepFreeze(x);}return v;}
deepFreeze(DATA);
const SECTORS=new Map(DATA.sectors.map(s=>[s.id,s])),INDUSTRIES=new Map(DATA.industries.map(s=>[s.id,s]));
const sectorName=id=>SECTORS.has(id)?SECTORS.get(id).name:id;
const industryName=id=>INDUSTRIES.has(id)?INDUSTRIES.get(id).name:id;
const sector=id=>SECTORS.get(id)||null;
return Object.freeze({DATA,VERSION:DATA.version,NAME:DATA.name,sectorName,industryName,sector});
});
"""


def render() -> str:
    return HEAD + json.dumps(current_taxonomy(), ensure_ascii=False, sort_keys=True, separators=(',', ':')) + TAIL


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        ok = OUT.is_file() and OUT.read_text(encoding='utf-8') == text
        print('COMMON_TAXONOMY_MAIN ' + ('ok' if ok else 'stale'))
        return 0 if ok else 1
    OUT.write_text(text, encoding='utf-8')
    print('COMMON_TAXONOMY_MAIN written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
