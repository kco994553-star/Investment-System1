"""Hand-counted result projection; never invoke scoring or raw transformation."""
from copy import deepcopy
import hashlib
import importlib.util
import json
from pathlib import Path

import pytest

from investment_system.research.sector_qgv import _input_identity, digest
from investment_system.research.sector_qgv_registry import ENGINE, MODEL, NORMALIZATION, MAPPING

DAY = '2026-11-04'
AT = DAY + 'T02:00:00Z'


def pin(root, name, value):
    path = root / name
    path.write_text(json.dumps(value, allow_nan=False))
    return {'path': str(path), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'ref': 'synthetic://' + name}


def inputs(root):
    """Two operating code rows share an issuer. Held cohort is 2 of 3 issuers."""
    job = {'schema_version': 'classification-counts-job/1', 'mode': 'summary-only',
           'data_kind': 'SYNTHETIC', 'valuation_date': DAY}
    for scope, members, issuers, axes in [
        ('operating', ['ROW:A', 'ROW:A.B'], ['A', 'A'], [(0, 50, None), (None, 20, None)]),
        ('expanded', ['ISSUER:A', 'ISSUER:B', 'ISSUER:C'], ['A', 'B', 'C'],
         [(0, 50, None), (None, 20, None), (80, None, None)])]:
        context = {'schema_version': 'common-classification-view/1',
                   'classification_hash': digest(scope), 'dictionary_version': 'common-industry-dictionary/2',
                   'mapping_version': 'common-classification-map/2', 'knowledge_as_of': '2026-11-08T00:00:00Z'}
        s = {'schema_version': 'sector-qgv-input/1', 'snapshot_id': scope + '-snapshot',
             'universe_id': scope, 'universe_version': 'fixture/1', 'input_version': 'common-classification-qgv/1',
             'mapping_version': MAPPING, 'as_of': AT, 'valuation_date': DAY, 'members': members,
             'classification_context': context, 'rows': []}
        for key, issuer in zip(members, issuers):
            gate = None if issuer == 'B' else {
                'q_industry_percentile': 0, 'calc_version': 'qgv2-calc/2026-10-23.1',
                'as_of': DAY, 'source_as_of': AT, 'derivation': 'OFFICIAL_Q_ONLY_REPLAY',
                'provenance': ['sec-qgv2.json#sha256=' + 'a' * 64]}
            s['rows'].append({'company_id': key, 'issuer_id': issuer, 'gate': gate})
        versions = dict(model_version=MODEL, engine_version=ENGINE, normalization_version=NORMALIZATION,
                        **{k: s[k] for k in ('mapping_version', 'input_version', 'snapshot_id', 'universe_id', 'universe_version')})
        p = {'schema_version': 'sector-qgv-preview/1', **versions, 'valuation_date': DAY, 'as_of': AT,
             'config_hash': 'c' * 64, 'input_hash': _input_identity(s), 'request_id': 'fixture',
             'validation_errors': [], 'result_rows': []}
        p['cache_key'] = digest(dict(config_hash=p['config_hash'], input_hash=p['input_hash'], **versions))
        p['preview_id'] = digest({'cache': p['cache_key'], 'request_id': p['request_id']})
        for key, issuer, values in zip(members, issuers, axes):
            p['result_rows'].append({'company_id': key, 'issuer_id': issuer, 'axes': dict(zip('QGV', values)),
                                     'total': None, 'status': 'STRICT_INCOMPLETE'})
        # These expectations are manually counted, not generated by the projection.
        q, g, n, ni = (1, 2, 2, 1) if scope == 'operating' else (2, 2, 3, 3)
        p['coverage'] = {'denominator': {'kind': 'ORIGINAL_MEMBER_ROWS', 'count': n, 'unique_issuers': ni},
                         'axes': {a: {'valid': x, 'denominator': n} for a, x in [('Q', q), ('G', g), ('V', 0)]},
                         'all_axes': {'valid': 0, 'denominator': n}, 'total': {'valid': 0, 'denominator': n}}
        view = {**context, **{k: s[k] for k in ('valuation_date', 'universe_id', 'universe_version', 'members')},
                'rows': [{'company_id': k, 'issuer_id': i} for k, i in zip(members, issuers)]}
        job[scope] = {k: pin(root, scope + '-' + k + '.json', value)
                      for k, value in [('snapshot', s), ('preview', p), ('view', view)]}
        job[scope]['expected'] = {k: s[k] for k in ('snapshot_id', 'universe_id', 'universe_version', 'as_of')}
        job[scope]['expected'].update(classification_hash=context['classification_hash'], config_hash=p['config_hash'])
    held = {'financials': {'A': {'state': 'LIVE'}, 'B': {'state': 'LIVE'}, 'C': {'state': 'NOT_AVAILABLE'}}}
    audit = {'connected': 2, 'rows': [
        {'company_id': 'ISSUER:' + i, 'issuer_id': i, 'status': 'UNAVAILABLE' if i == 'B' else 'CONNECTED',
         'reason': 'MISSING_INPUT' if i == 'B' else None, 'gate_source_sha256': 'a' * 64,
         'gate_universe_id': 'operating', 'gate_universe_version': 'fixture/1',
         'scope': 'RETAINED_UNIVERSE504_OFFICIAL_Q_REPLAY_NOT_EXPANDED_Q'} for i in 'ABC']}
    outer = {'schema_version': 'held-expanded-classification-summary/1', 'valuation_date': DAY,
             'catalog_observed_at': '2026-10-01T00:00:00Z', 'catalog_age_days': 34,
             'population_kind': 'OBSERVED_CATALOG_ISSUERS_NOT_INVESTMENT_ELIGIBLE_UNIVERSE',
             'new_security_ids': 0, 'official_universe_changed': False,
             'rank_scope': 'ISSUER_SAMPLE_SECTOR_DIAGNOSTIC_NOT_MARKET_RANK',
             'catalog': {'issuers': 3, 'Q': 2, 'G': 2, 'V': 0, 'joint': 0, 'total': 0},
             'held_financial_subsample': {'issuers': 2, 'Q': 1, 'G': 2, 'V': 0, 'joint': 0, 'total': 0},
             'official_gate_connected': 2, 'full_market_denominator': None, 'full_market_coverage': None}
    for name, n in [('catalog', 3), ('held_financial_subsample', 2)]:
        outer[name].update(ticker_observations=n, sector=n, accounting=n, industry=0, raw=n, factor_score=n)
    for key, value in [('held', held), ('gate_linkage', audit), ('summary', outer)]:
        job[key] = pin(root, key + '.json', value)
    return job


def rewrite(job, root, scope, key, mutate):
    spec = job[scope][key] if scope else job[key]
    data = json.loads(Path(spec['path']).read_text())
    mutate(data)
    updated = pin(root, Path(spec['path']).name, data)
    if scope:
        job[scope][key] = updated
    else:
        job[key] = updated


def project(job):
    from investment_system.research.classification_counts import summarize
    return summarize(job)


def test_manual_counts_keep_rows_issuers_gate_zero_and_unmeasured_separate(tmp_path):
    job = inputs(tmp_path)
    before = deepcopy(job)
    out = project(job)
    c = out['calculation_counts']['scopes']
    op, held, catalog = [c[x] for x in ('operating', 'held_financial_subsample', 'catalog')]
    assert op['population']['denominator'] == 2 and op['population']['unique_issuers'] == 1
    assert op['population']['unit'] == 'CODE_ROW'
    assert [op['counts'][a]['valid'] for a in 'QGV'] == [1, 2, 0]
    assert op['counts']['V']['status'] == 'NOT_COMPUTED'
    assert op['official_q_gate_input']['status'] == 'NOT_MEASURED'
    assert op['official_q_gate_input']['valid'] is None
    assert held['population']['denominator'] == 2 and held['population']['unit'] == 'ISSUER'
    assert held['scoring_population']['denominator'] == 3
    assert held['official_q_gate_input']['valid'] == 1
    assert catalog['official_q_gate_input']['valid'] == 2
    assert held['counts']['Q']['valid'] == 1 and catalog['counts']['Q']['valid'] == 2
    assert out['full_market_denominator'] is None and out['full_market_coverage'] is None
    assert out['official_gate_connected'] == 2 and job == before
    assert 'result_rows' not in json.dumps(out['calculation_counts'])


def test_main_fixture_matches_projected_bytes(tmp_path):
    fixture = Path(__file__).parents[1] / 'fixtures/classification_counts/summary.json'
    actual = (json.dumps(project(inputs(tmp_path)), ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode()
    assert fixture.read_bytes() == actual


@pytest.mark.parametrize('change,match', [
    ('hash', 'INPUT_HASH_MISMATCH'), ('date', 'CONTEXT_MISMATCH'),
    ('snapshot', 'CONTEXT_MISMATCH'), ('population', 'CONTEXT_MISMATCH'),
    ('classification', 'CLASSIFICATION_MISMATCH'), ('versions', 'CLASSIFICATION_VERSION'),
    ('input_hash', 'PREVIEW_IDENTITY'), ('engine', 'ENGINE_VERSION'),
    ('missing_axis', 'MISSING_FIELD'), ('boolean_score', 'INVALID_SCORE'),
    ('duplicate', 'DUPLICATE_ROW'), ('missing_row', 'MEMBERS_MISMATCH'),
    ('issuer', 'ISSUER_MISMATCH'), ('coverage', 'COUNT_MISMATCH'),
    ('held_missing_state', 'MISSING_FIELD'), ('held_outside', 'HELD_OUTSIDE_CATALOG'),
    ('gate_day', 'PREVIEW_IDENTITY'), ('gate_status', 'GATE_LINKAGE_MISMATCH'),
    ('outer_count', 'COUNT_MISMATCH'), ('full_market', 'FULL_MARKET_UNMEASURED'),
    ('stale_cutoff', 'CONTEXT_MISMATCH'), ('config', 'PREVIEW_IDENTITY'),
    ('gate_source', 'GATE_LINKAGE_MISMATCH'), ('held_duplicate_issuer', 'DUPLICATE_ISSUER'),
])
def test_reject_mixed_stale_incomplete_or_tampered_artifacts(tmp_path, change, match):
    job = inputs(tmp_path)
    mutations = {
        'date': ('operating', 'preview', lambda d: d.update(valuation_date='2026-11-02')),
        'snapshot': ('operating', 'preview', lambda d: d.update(snapshot_id='old')),
        'population': ('operating', 'preview', lambda d: d.update(universe_id='other')),
        'classification': ('operating', 'view', lambda d: d.update(classification_hash='f' * 64)),
        'versions': ('operating', 'view', lambda d: d.update(mapping_version='common-classification-map/1')),
        'input_hash': ('operating', 'preview', lambda d: d.update(input_hash='f' * 64)),
        'engine': ('operating', 'preview', lambda d: d.update(engine_version='other')),
        'missing_axis': ('operating', 'preview', lambda d: d['result_rows'][0]['axes'].pop('G')),
        'boolean_score': ('operating', 'preview', lambda d: d['result_rows'][0]['axes'].update(Q=False)),
        'duplicate': ('operating', 'preview', lambda d: d['result_rows'].append(deepcopy(d['result_rows'][0]))),
        'missing_row': ('operating', 'preview', lambda d: d['result_rows'].pop()),
        'issuer': ('operating', 'preview', lambda d: d['result_rows'][0].update(issuer_id='B')),
        'coverage': ('operating', 'preview', lambda d: d['coverage']['axes']['Q'].update(valid=2)),
        'held_missing_state': (None, 'held', lambda d: d['financials']['A'].pop('state')),
        'held_outside': (None, 'held', lambda d: d['financials'].update(D={'state': 'LIVE'})),
        'gate_day': ('expanded', 'snapshot', lambda d: d['rows'][0]['gate'].update(as_of='2026-11-02')),
        'gate_status': (None, 'gate_linkage', lambda d: d['rows'][1].update(status='CONNECTED')),
        'outer_count': (None, 'summary', lambda d: d['held_financial_subsample'].update(Q=2)),
        'full_market': (None, 'summary', lambda d: d.update(full_market_denominator=3)),
        'stale_cutoff': ('expanded', 'preview', lambda d: d.update(as_of='2026-11-03T02:00:00Z')),
        'config': ('operating', 'preview', lambda d: d.update(config_hash='d' * 64)),
        'gate_source': (None, 'gate_linkage', lambda d: d['rows'][0].update(gate_source_sha256='b' * 64)),
    }
    if change == 'hash':
        job['operating']['preview']['sha256'] = '0' * 64
    elif change == 'held_duplicate_issuer':
        # All three source artifacts agree, but an issuer-count scope may not count
        # two code rows as two issuers. Keep operating multi-class rows allowed.
        for key, rowskey in [('snapshot', 'rows'), ('preview', 'result_rows'), ('view', 'rows')]:
            rewrite(job, tmp_path, 'expanded', key, lambda d: d[rowskey][1].update(issuer_id='A'))
        s = json.loads(Path(job['expanded']['snapshot']['path']).read_text())
        def identities(p):
            p['coverage']['denominator']['unique_issuers'] = 2
            p['input_hash'] = _input_identity(s)
            versions = {k: p[k] for k in ('model_version', 'engine_version', 'normalization_version', 'mapping_version', 'input_version', 'snapshot_id', 'universe_id', 'universe_version')}
            p['cache_key'] = digest(dict(config_hash=p['config_hash'], input_hash=p['input_hash'], **versions))
            p['preview_id'] = digest({'cache': p['cache_key'], 'request_id': p['request_id']})
        rewrite(job, tmp_path, 'expanded', 'preview', identities)
        rewrite(job, tmp_path, None, 'held', lambda d: d['financials'].pop('B'))
    else:
        rewrite(job, tmp_path, *mutations[change])
    with pytest.raises(ValueError, match=match):
        project(job)


@pytest.mark.parametrize('value', [float('nan'), float('inf'), -1, 101])
def test_nonfinite_or_out_of_range_score_is_not_a_count(tmp_path, value):
    job = inputs(tmp_path)
    spec = job['operating']['preview']
    p = Path(spec['path'])
    d = json.loads(p.read_text())
    d['result_rows'][0]['axes']['Q'] = value
    p.write_text(json.dumps(d))
    spec['sha256'] = hashlib.sha256(p.read_bytes()).hexdigest()
    with pytest.raises(ValueError, match='INVALID_SCORE'):
        project(job)


def test_existing_cli_summary_mode_never_calls_engine_or_normalizer(tmp_path, monkeypatch):
    spec = importlib.util.spec_from_file_location('counts_cli', Path(__file__).parents[2] / 'tools/expanded_held_classification.py')
    cli = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cli)
    monkeypatch.setattr(cli, 'build', lambda *a: pytest.fail('full calculation called'))
    job = inputs(tmp_path)
    out = tmp_path / 'output'
    result = cli.run(job, out, synthetic=True)
    assert result['calculation_counts']['scopes']['operating']['counts']['Q']['valid'] == 1
    manifest = json.loads((out / 'manifest.json').read_text())
    for row in manifest['files']:
        assert hashlib.sha256((out / row['path']).read_bytes()).hexdigest() == row['sha256']
    assert not (out / 'preview.json').exists()
    assert not (out / 'classification-summary.csv').exists()
    with pytest.raises(ValueError, match='OUTPUT_ALREADY_EXISTS'):
        cli.run(job, out, synthetic=True)
