"""Reviewed Korean company-name table (Pages file ``company-names-ko.json``, owner decision KR-NAMES 2026-10-18).

Display and search only. A name never changes a QGV calculation, company identity, ranking or a past record.

Keys are the identifiers the app already uses (never a ticker alone, no new identification scheme):
- ``TARGET_COMPANY_ID``: a TARGET company_id (``markets.us.US_LISTINGS`` + ``OUT_OF_US_TRACK``). When
  ``US_LISTINGS[company_id]`` names a Universe504 code (exchange + symbol) whose Universe-registry CIK equals the
  listing's CIK, that code is stored in ``universe_code`` and gets no record of its own (the same rule
  ``sec_m3_adapter`` uses to put a TARGET company_id on a Universe row).
- ``UNIVERSE_CODE``: every other Universe504 code (``universe_codes_v1.json``); ``universe_code`` equals the key.
``cik`` is a cross-check only.

Korean names: ``OFFICIAL`` (an official Korean source, URL), ``COMMON`` (Wikidata Korean label / Korean Wikipedia
title tied to the same SEC CIK or listing, QID or URL), else ``UNREGISTERED`` with ``ko_name`` null. Nobody's own
translation or transliteration is ever stored. The reviewed file lives in web_assets and is regenerated by
``tools/build_company_names_ko.py`` from saved inputs; the guard accepts only that exact reviewed file.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import unicodedata

from .universe_codes import source_codes

FILENAME = 'company-names-ko.json'
SCHEMA = 'company-names-ko/1'
SOURCE = Path(__file__).parents[1] / 'product/web_assets' / FILENAME
MAX_BYTES = 1024 * 1024
KEY_KINDS = ('TARGET_COMPANY_ID', 'UNIVERSE_CODE')
KO_STATUSES = ('OFFICIAL', 'COMMON', 'UNREGISTERED')
CLASS_LABELS = ('A', 'B', 'C')
TOP_KEYS = ['schema', 'generated_by', 'reviewed_at', 'policy', 'inputs', 'counts', 'records']
RECORD_KEYS = ['key', 'key_kind', 'universe_code', 'cik', 'ticker', 'exchange', 'share_class_note', 'class_label',
               'en_name', 'en_source', 'ko_name', 'ko_status', 'ko_source', 'aliases', 'reviewed_at']
COUNT_KEYS = ['records', 'target_company_ids', 'universe_codes', 'official', 'common', 'unregistered',
              'en_name_present', 'en_name_missing']
_CODE = re.compile(r'(NYSE|NASDAQ|BATS):([A-Z][A-Z0-9.]{0,15})')
_DAY = re.compile(r'\d{4}-\d{2}-\d{2}')
_SHA = re.compile(r'[0-9a-f]{64}')
_SOURCE = re.compile(r'https://[A-Za-z0-9.\-]+\.[a-z]{2,}/[^\s"<>]{0,300}')
_HANGUL = re.compile(r'[가-힣]')


def target_listings() -> dict:
    """{company_id: listing or None} for the 19 TARGET companies (None: no US listing, no CIK)."""
    from ..markets.us import OUT_OF_US_TRACK, US_LISTINGS
    out = {cid: dict(v) for cid, v in US_LISTINGS.items()}
    out.update({cid: None for cid in OUT_OF_US_TRACK})
    return out


def compact(text: str) -> str:
    """Case- and space-insensitive comparison form (same idea as EntitySearch.normalize without spaces)."""
    return re.sub(r'[^\w]+', '', unicodedata.normalize('NFKC', str(text)).casefold().replace('_', ''))


def source_payload() -> dict:
    return json.loads(SOURCE.read_text(encoding='utf-8'))


def public_payload() -> dict:
    payload = source_payload()
    require_company_names_ko(payload, reviewed=payload)
    return payload


def _text(value, limit=200):
    return type(value) is str and 0 < len(value) <= limit and value == value.strip() and not any(ord(c) < 32 for c in value)


def _need(ok):
    if not ok:
        raise ValueError('company names ko invalid')


def check_shape(value) -> None:
    """Strict shape and invariants, independent of the reviewed file (used by the build tool and its tests)."""
    _need(type(value) is dict and list(value) == TOP_KEYS and value['schema'] == SCHEMA)
    _need(_text(value['generated_by']) and type(value['reviewed_at']) is str and _DAY.fullmatch(value['reviewed_at']))
    _need(type(value['policy']) is list and 0 < len(value['policy']) <= 12 and all(_text(x, 400) for x in value['policy']))
    inputs = value['inputs']
    _need(type(inputs) is list and 0 < len(inputs) <= 8)
    _need(all(type(i) is dict and list(i) == ['name', 'sha256'] and _text(i['name'], 64) and type(i['sha256']) is str
              and _SHA.fullmatch(i['sha256']) for i in inputs))
    records = value['records']
    _need(type(records) is list and 0 < len(records) <= 1100)
    codes, listings = source_codes(), target_listings()
    seen_keys, seen_codes, targets = set(), [], []
    for r in records:
        _need(type(r) is dict and list(r) == RECORD_KEYS)
        _need(r['key_kind'] in KEY_KINDS and _text(r['key'], 64) and r['key'] not in seen_keys)
        seen_keys.add(r['key'])
        _need(r['cik'] is None or type(r['cik']) is str and re.fullmatch(r'[0-9]{10}', r['cik']) and r['cik'] != '0000000000')
        _need(_text(r['ticker'], 16) and _text(r['exchange'], 16))
        code = r['universe_code']
        if r['key_kind'] == 'UNIVERSE_CODE':
            # The Universe code is the identifier; ticker / exchange are only its two parts.
            m = _CODE.fullmatch(r['key'])
            _need(m is not None and code == r['key'] and (m.group(1), m.group(2)) == (r['exchange'], r['ticker']))
            _need(r['key'] not in listings)
        else:
            _need(r['key'] in listings)
            targets.append(r['key'])
            listing = listings[r['key']]
            if listing is None:
                _need(code is None and r['cik'] is None)
            else:
                # Linked only through the existing TARGET listing map: CIK and exchange:symbol must both agree.
                _need(r['cik'] == listing['cik'] and r['exchange'] == listing['exchange'] and r['ticker'] == listing['yahoo'])
                _need(code is None or code == listing['exchange'] + ':' + listing['yahoo'])
        if code is not None:
            _need(code in codes)
            seen_codes.append(code)
        _need(r['class_label'] is None or r['class_label'] in CLASS_LABELS)
        _need((r['class_label'] is None) == (r['share_class_note'] is None))
        _need(r['share_class_note'] is None or _text(r['share_class_note'], 200))
        _need((r['en_name'] is None) == (r['en_source'] is None))
        _need(r['en_name'] is None or _text(r['en_name'], 160) and _text(r['en_source'], 300))
        _need(r['ko_status'] in KO_STATUSES)
        if r['ko_status'] == 'UNREGISTERED':
            _need(r['ko_name'] is None and r['ko_source'] is None)
        else:
            _need(_text(r['ko_name'], 80) and type(r['ko_source']) is str and _SOURCE.fullmatch(r['ko_source']))
            # A COMMON name is a Korean-script name; an OFFICIAL one may be the Latin brand the official Korean page uses.
            _need(r['ko_status'] == 'OFFICIAL' or _HANGUL.search(r['ko_name']))
        aliases = r['aliases']
        _need(type(aliases) is list and len(aliases) <= 12)
        forms = {compact(r['ko_name'])} if r['ko_name'] else set()
        for a in aliases:
            _need(type(a) is dict and list(a) == ['text', 'lang', 'source'] and _text(a['text'], 80) and a['lang'] in ('ko', 'en'))
            _need(type(a['source']) is str and _SOURCE.fullmatch(a['source']) is not None)
            form = compact(a['text'])
            _need(form and form not in forms)  # unique per company, and never a copy of the Korean name
            forms.add(form)
        _need(type(r['reviewed_at']) is str and _DAY.fullmatch(r['reviewed_at']) and r['reviewed_at'] <= value['reviewed_at'])
    # Every Universe code and every TARGET company_id exactly once.
    _need(sorted(seen_codes) == sorted(codes) and len(seen_codes) == len(set(seen_codes)))
    _need(sorted(targets) == sorted(listings))
    counts = value['counts']
    _need(type(counts) is dict and list(counts) == COUNT_KEYS)
    expect = {'records': len(records), 'target_company_ids': len(targets), 'universe_codes': len(seen_codes),
              'official': sum(r['ko_status'] == 'OFFICIAL' for r in records),
              'common': sum(r['ko_status'] == 'COMMON' for r in records),
              'unregistered': sum(r['ko_status'] == 'UNREGISTERED' for r in records),
              'en_name_present': sum(r['en_name'] is not None for r in records),
              'en_name_missing': sum(r['en_name'] is None for r in records)}
    _need(counts == expect)
    # Keys are fixed above (no price / rank / holding fields can exist); no contact address in any value.
    _need('@' not in json.dumps(value, ensure_ascii=False))
    _need(len(json.dumps(value, ensure_ascii=False, separators=(',', ':')).encode()) <= MAX_BYTES)


def require_company_names_ko(value, *, reviewed=None) -> None:
    """Guard check: strict shape and equal to the reviewed in-repo file (web_assets/company-names-ko.json)."""
    try:
        check_shape(value)
    except (TypeError, KeyError, AttributeError):
        raise ValueError('company names ko invalid') from None
    if value != (source_payload() if reviewed is None else reviewed):
        raise ValueError('company names ko differ from the reviewed file')


def alias_collisions(value) -> list:
    """[(compact form, [keys])] where one name or alias form belongs to more than one record (reported, not an error)."""
    owners = {}
    for r in value['records']:
        texts = ([r['ko_name']] if r['ko_name'] else []) + [a['text'] for a in r['aliases']]
        for text in texts:
            owners.setdefault(compact(text), set()).add(r['key'])
    return sorted((form, sorted(keys)) for form, keys in owners.items() if len(keys) > 1)
