"""Static News | Network page for one ``RIGViewModel``. NEW IMPLEMENTATION.

The page swaps the whole content area between News and Network (no side-by-side
split). Zoom (wheel/pinch), pan (drag on empty space), node drag, node/edge quick
view, double-click focus, ``+N`` expansion, fit and search run client-side over
the embedded, already-projected model; the page never fetches or scores anything.
Later phases add presentation through ``PageExtras`` without editing this module.
"""

from __future__ import annotations

import html
import json
from dataclasses import dataclass, field

from .labels import TERMS, Language, term
from .views import RIGViewModel, ViewKind


@dataclass(frozen=True)
class PageExtras:
    card_badges: dict = field(default_factory=dict)  # event_id -> tuple[str, ...] (term keys)
    edge_badges: dict = field(default_factory=dict)  # relationship_id -> tuple[str, ...] (term keys, max 2 shown)
    edge_width: dict = field(default_factory=dict)  # relationship_id -> float
    node_symbol: dict = field(default_factory=dict)  # node_id -> symbol
    toolbar_html: str = ""  # trusted, generated by later RIG phases only
    terms: dict = field(default_factory=dict)  # key -> (en, ko)
    card_order: tuple = ()  # optional event_id order (feed priority); default = model order


MAX_EDGE_BADGES = 2

