def _e(s) -> str:
    return html.escape(str(s), quote=True)


def _t(key: str, lang: Language, extras: PageExtras, prefix: str = "") -> str:
    return (f'<span data-term="{_e(key)}" data-prefix="{_e(prefix)}">'
            f'{_e(prefix + term(key, lang, extras.terms))}</span>')


def render_page(vm: RIGViewModel, lang: Language = Language.KO, extras: PageExtras | None = None) -> str:
    x = extras or PageExtras()
    net = vm.network
    names = {n.issuer_id: n.label for n in net.nodes}
    cards = {c.event_id: c for c in vm.cards}
    order = [i for i in x.card_order if i in cards] + [c.event_id for c in vm.cards if c.event_id not in x.card_order]
    card_html = []
    for eid in order:
        c = cards[eid]
        badges = "".join(f'<span class="badge">{_t(b, lang, x)}</span>' for b in (c.status.value,) + tuple(
            x.card_badges.get(eid, ())))
        who = ", ".join(_e(names.get(i, i)) for i in c.issuer_ids)
        summary = "".join(f"<p>{_e(s)}</p>" for s in c.summary)
        card_html.append(
            f'<article class="card" data-event="{_e(eid)}">{badges}<h3>{_e(c.headline)}</h3>'
            f'<div class="meta">{who} · {_e(c.available_at.isoformat())} · {c.source_count} {_t("sources", lang, x)}</div>'
            f'{summary}<details><summary>{_t("more", lang, x)}</summary><div class="meta">'
            f'{_e(" ".join(c.relationship_ids))}</div><p class="note">{_t("evidence_note", lang, x)}</p></details></article>')
    if not card_html:
        card_html.append(f'<p class="note">{_t("no_news", lang, x)}</p>')
    pos = {n.node_id: n for n in net.nodes}
    svg = ['<defs><marker id="arr" viewBox="0 0 10 10" refX="22" refY="5" markerWidth="7" markerHeight="7" '
           'orient="auto-start-reverse"><path d="M0,0L10,5L0,10z" fill="currentColor"/></marker></defs><g id="vp">']
    for ed in net.edges:
        a, b = pos[ed.source_node_id], pos[ed.target_node_id]
        cls = "inf" if ed.line == "DASHED" else "fact"
        width = x.edge_width.get(ed.relationship_id, 1.5)
        badges = tuple(x.edge_badges.get(ed.relationship_id, ()))[:MAX_EDGE_BADGES]
        title = " · ".join([term(ed.relationship_type.value, lang, x.terms), term(ed.epistemic.value, lang, x.terms)]
                           + [term(k, lang, x.terms) for k in badges])
        marker = ' marker-end="url(#arr)"' if ed.arrow else ""
        svg.append(
            f'<line id="e-{_e(ed.relationship_id)}" data-edge="{_e(ed.relationship_id)}" class="{cls}" '
            f'x1="{a.x}" y1="{a.y}" x2="{b.x}" y2="{b.y}" stroke-width="{width}"{marker}><title>{_e(title)}</title></line>')
    for n in net.nodes:
        sym = x.node_symbol.get(n.node_id, n.symbol)
        svg.append(f'<g id="n-{_e(n.node_id)}" data-node="{_e(n.node_id)}" transform="translate({n.x} {n.y})">'
                   f'<circle r="16"/><text text-anchor="middle" dy="5">{_e(sym)}</text>'
                   f'<text text-anchor="middle" dy="36">{_e(n.label)}</text></g>')
    svg.append("</g>")
    data = {
        "lang": lang.value, "view": vm.state.view.value, "focus": vm.state.focus_node_id,
        "steps": vm.state.expansion_steps, "limit": 8, "hidden": net.hidden_edge_count,
        "viewport": {"zoom": vm.state.viewport.zoom, "pan_x": vm.state.viewport.pan_x,
                     "pan_y": vm.state.viewport.pan_y},
        "terms": {**TERMS, **x.terms},
        "nodes": [{"id": n.node_id, "issuer": n.issuer_id, "label": n.label, "x": n.x, "y": n.y} for n in net.nodes],
        "edges": [{"id": e.relationship_id, "s": e.source_node_id, "t": e.target_node_id,
                   "type": e.relationship_type.value, "ep": e.epistemic.value, "at": e.available_at.isoformat(),
                   "lc": e.last_confirmed_at.isoformat()} for e in net.edges],
        "order": net.neighbor_order,
    }
    payload = json.dumps(data, ensure_ascii=False, sort_keys=True).replace("</", "<\\/")
    opts = "".join(f'<option value="{l.value}"{" selected" if l is lang else ""}>{v}</option>'
                   for l, v in ((Language.EN, "English"), (Language.EN_KO, "English (한국어)"), (Language.KO, "한국어")))
    return f"""<!DOCTYPE html>
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>RIG News Network</title><style>{CSS}</style></head><body>
<header><h1>{_t("news", lang, x)}</h1>
<div class="seg" role="group"><button data-view="NEWS">{_t("news", lang, x)}</button><button data-view="NETWORK">{_t("network", lang, x)}</button></div>
<div class="tb">{x.toolbar_html}<select id="lang" aria-label="language">{opts}</select>
<span class="meta">{_t("as_of", lang, x)} {_e(vm.graph_as_of.isoformat())}</span></div></header>
<main><section id="pane-NEWS">{"".join(card_html)}</section>
<section id="pane-NETWORK" hidden><div class="tb"><input id="q" type="search">
<button id="fit" title="fit">⌂ {_t("fit", lang, x)}</button><button id="more" hidden>{_t("more_relationships", lang, x)}</button></div>
<svg id="net" viewBox="0 0 1000 1000" role="img" aria-label="network">{"".join(svg)}</svg><div id="qv"></div></section></main>
<script type="application/json" id="rig-data">{payload}</script><script>{JS}</script></body></html>"""
